"""
Write a trained scikit-learn random forest as eog_model.h: constant C tables the board walks in eog.c.

Per node: feature index (-1 = leaf), float32 threshold, left child, right child; leaves carry the class
probabilities [none, blink, left, right]. eog.c averages the leaf probabilities over the trees, which is
what RandomForestClassifier.predict_proba does, and check() confirms the two agree.
"""
import numpy as np


def _flatten(model):
    nodes, roots = [], []
    for est in model.estimators_:
        t = est.tree_
        roots.append(len(nodes))
        base = len(nodes)
        for i in range(t.node_count):
            if t.children_left[i] == -1:
                v = t.value[i][0]
                nodes.append((-1, 0.0, 0, 0, v / v.sum()))
            else:
                nodes.append((int(t.feature[i]), float(np.float32(t.threshold[i])),
                              base + int(t.children_left[i]), base + int(t.children_right[i]), None))
    return nodes, roots


def _f(x):
    s = f"{x:.9g}"
    return (s if any(c in s for c in ".en") else s + ".0") + "f"


def write_header(model, path, max_depth):
    nodes, roots = _flatten(model)
    nc = len(model.classes_)
    assert list(model.classes_) == list(range(nc)), "classes must be 0..3 (none, blink, left, right)"
    assert len(nodes) < 65536, "node indices must fit in unsigned short"
    with open(path, "w") as h:
        h.write(f"/* Auto-generated by training/export_model.py: random forest, {len(roots)} trees, "
                f"max depth {max_depth}, {len(nodes)} nodes */\n#ifndef EOG_MODEL_H\n#define EOG_MODEL_H\n")
        h.write(f"#define RF_NTREES {len(roots)}\n#define RF_NNODES {len(nodes)}\n"
                f"#define RF_NFEAT {model.n_features_in_}\n#define RF_NCLASS {nc}\n")
        h.write("static const int RF_ROOT[RF_NTREES]={" + ",".join(map(str, roots)) + "};\n")
        h.write("/* per node: feature (-1 = leaf), threshold, left child, right child; go left if x[feature] <= threshold */\n")
        h.write("static const short RF_FEAT[RF_NNODES]={" + ",".join(str(n[0]) for n in nodes) + "};\n")
        h.write("static const float RF_THR[RF_NNODES]={" + ",".join(_f(n[1]) for n in nodes) + "};\n")
        h.write("static const unsigned short RF_LEFT[RF_NNODES]={" + ",".join(str(n[2]) for n in nodes) + "};\n")
        h.write("static const unsigned short RF_RIGHT[RF_NNODES]={" + ",".join(str(n[3]) for n in nodes) + "};\n")
        h.write("/* class probabilities [none,blink,left,right] for every node (zero for internal nodes) */\n")
        h.write("static const float RF_PROB[RF_NNODES][RF_NCLASS]={" + ",".join(
            "{" + ",".join(_f(v) for v in (n[4] if n[4] is not None else [0] * nc)) + "}" for n in nodes) + "};\n#endif\n")
    return nodes, roots


def check(model, X, n=500):
    """Largest difference between the exported tree walk (as eog.c does it) and predict_proba."""
    nodes, roots = _flatten(model)
    X = np.asarray(X, dtype=np.float32)[:n]
    worst = 0.0
    for x, ref in zip(X, model.predict_proba(X)):
        p = np.zeros(len(model.classes_))
        for r in roots:
            i = r
            while nodes[i][0] != -1:
                i = nodes[i][2] if x[nodes[i][0]] <= np.float32(nodes[i][1]) else nodes[i][3]
            p += nodes[i][4]
        worst = max(worst, float(np.abs(p / len(roots) - ref).max()))
    return worst
